// middleware/uploadMiddleware.js
// File uploads with Multer, saved to disk in backend/uploads/<folder>/.
//
// Three checks protect the server:
//   1. MIME type AND file extension must both be on the allow-list
//      (checked BEFORE anything is written to disk)
//   2. File size limit (Multer stops reading and deletes the partial file)
//   3. "Magic bytes": after saving, we read the first bytes of the file and
//      confirm it really is a JPEG / PNG / WebP / PDF. The MIME type and the
//      extension are chosen by the client and can lie; the content can't.
//
// Filenames are generated by us (timestamp + random hex + safe extension).
// The user's original filename is never used on disk.
//
// Usage in a route (always AFTER requireAuth, so anonymous users can't upload):
//   router.put('/me', requireAuth, requireRole('employee'), uploadProfilePhoto, controller.update);
// The controller then finds the file in req.file (or undefined if none was sent).

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const multer = require('multer');
const { UPLOAD_ROOT, removeUploadedFile } = require('../utils/files');

const MB = 1024 * 1024;

// MIME type -> allowed extensions, and the extension we save with
const FILE_TYPES = {
  'image/jpeg': { extensions: ['.jpg', '.jpeg'], saveAs: '.jpg', label: 'JPEG' },
  'image/png': { extensions: ['.png'], saveAs: '.png', label: 'PNG' },
  'image/webp': { extensions: ['.webp'], saveAs: '.webp', label: 'WebP' },
  'application/pdf': { extensions: ['.pdf'], saveAs: '.pdf', label: 'PDF' },
};

const IMAGE_TYPES = ['image/jpeg', 'image/png', 'image/webp'];
const DOCUMENT_TYPES = ['application/pdf', 'image/jpeg', 'image/png'];

// Reads the first bytes of a saved file and checks its real format.
async function hasValidSignature(filePath, mimeType) {
  const handle = await fs.promises.open(filePath, 'r');
  try {
    const buffer = Buffer.alloc(12);
    await handle.read(buffer, 0, 12, 0);
    switch (mimeType) {
      case 'image/jpeg':
        return buffer[0] === 0xff && buffer[1] === 0xd8 && buffer[2] === 0xff;
      case 'image/png':
        return buffer.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]));
      case 'image/webp':
        return buffer.toString('ascii', 0, 4) === 'RIFF' && buffer.toString('ascii', 8, 12) === 'WEBP';
      case 'application/pdf':
        return buffer.toString('ascii', 0, 5) === '%PDF-';
      default:
        return false;
    }
  } finally {
    await handle.close();
  }
}

function uploadError(statusCode, message) {
  return { statusCode, message };
}

// Turns any Multer/busboy error into { statusCode, message } for the client,
// or null if it is a real server problem (disk full, permissions...).
function describeUploadError(err, { fieldName, maxSizeMb }) {
  if (err.statusCode) return uploadError(err.statusCode, err.message); // our own fileFilter error

  if (err instanceof multer.MulterError) {
    switch (err.code) {
      case 'LIMIT_FILE_SIZE':
        return uploadError(413, `File is too large. Maximum size is ${maxSizeMb} MB.`);
      case 'LIMIT_UNEXPECTED_FILE':
        return uploadError(400, `Unexpected file field "${err.field}". Send the file in the field "${fieldName}".`);
      case 'LIMIT_FILE_COUNT':
        return uploadError(400, 'Only one file can be uploaded at a time.');
      default:
        return uploadError(400, `Upload error: ${err.message}`);
    }
  }

  // Operating-system errors (ENOSPC, EACCES...) are server problems -> 500
  if (err.code && /^E[A-Z]+$/.test(err.code)) return null;

  // Anything else comes from parsing a broken multipart body
  return uploadError(400, `Could not read the uploaded form data: ${err.message}`);
}

// Builds an upload middleware for ONE optional file in ONE field.
function createUploader({ folder, fieldName, allowedTypes, maxSizeMb }) {
  const allowedLabels = allowedTypes.map((type) => FILE_TYPES[type].label).join(', ');

  const multerInstance = multer({
    storage: multer.diskStorage({
      destination: path.join(UPLOAD_ROOT, folder),
      filename: (req, file, cb) => {
        const safeName = `${Date.now()}-${crypto.randomBytes(8).toString('hex')}${FILE_TYPES[file.mimetype].saveAs}`;
        cb(null, safeName);
      },
    }),
    limits: {
      fileSize: maxSizeMb * MB,
      files: 1,     // at most one file per request
      fields: 20,   // text fields that come with the file
      parts: 25,
    },
    fileFilter: (req, file, cb) => {
      const type = FILE_TYPES[file.mimetype];
      const extension = path.extname(file.originalname || '').toLowerCase();
      if (!allowedTypes.includes(file.mimetype) || !type.extensions.includes(extension)) {
        return cb(Object.assign(new Error(`Invalid file type. Allowed: ${allowedLabels}.`), { statusCode: 400 }));
      }
      cb(null, true);
    },
  });

  const parseSingleFile = multerInstance.single(fieldName);

  return (req, res, next) => {
    parseSingleFile(req, res, async (err) => {
      if (err) {
        const clientError = describeUploadError(err, { fieldName, maxSizeMb });
        return clientError
          ? res.status(clientError.statusCode).json({ success: false, message: clientError.message })
          : next(err);
      }

      if (!req.file) return next(); // no file sent - that's the controller's decision

      try {
        if (!(await hasValidSignature(req.file.path, req.file.mimetype))) {
          await removeUploadedFile(req.file);
          return res.status(400).json({
            success: false,
            message: `The file content is not a valid ${FILE_TYPES[req.file.mimetype].label} file.`,
          });
        }
        next();
      } catch (checkError) {
        await removeUploadedFile(req.file);
        next(checkError);
      }
    });
  };
}

// The three uploaders used by the routes
const uploadProfilePhoto = createUploader({
  folder: 'profiles',
  fieldName: 'profile_photo',
  allowedTypes: IMAGE_TYPES,
  maxSizeMb: 2,
});

const uploadAttendancePhoto = createUploader({
  folder: 'attendance',
  fieldName: 'attendance_photo',
  allowedTypes: IMAGE_TYPES,
  maxSizeMb: 2,
});

const uploadDocument = createUploader({
  folder: 'documents',
  fieldName: 'document',
  allowedTypes: DOCUMENT_TYPES,
  maxSizeMb: 5,
});

module.exports = { uploadProfilePhoto, uploadAttendancePhoto, uploadDocument };
